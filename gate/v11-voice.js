function gateV11ChooseVoice(p,sections){
 if(!p||!Array.isArray(p.choices)||p.choices.length<8)return sections.line;
 const primary=sections.pri,secondary=sections.other;
 const group=GATE_V11_VOICES[primary.id];
 if(!group)return sections.line;
 const axes=Array.isArray(p.axes)?p.axes:[];
 const priorities={
  "보호":[.05,.15,.45,.35],"지속":[.1,.05,.2,.45],
  "돌파":[.3,.3,.1,.3],"검증":[.4,.3,.15,.15],
  "조율":[.25,.15,.4,.2],"통제":[.3,.3,.2,.2],
  "변경":[.2,.45,.15,.2],"귀환":[.15,.25,.15,.45]
 };
 const boosts=priorities[primary.id]||[.25,.25,.25,.25];
 const ranked=GATE_V11_VOICE_SCENES.map((index,order)=>{
  const scenario=gateV8Choice(p,index);
  const axis=scenario.choice.axis,scale=Number.isFinite(axes[axis])?axes[axis]:5;
  const topMatch=axis===primary.axis?1.65:axis===primary.side?.55:0;
  const secondMatch=axis===secondary.axis?.42:0;
  // A choice is more representative when its axis score is higher than
  // the overall tactic baseline; the follow-up motive decides close cases.
  const avg=axes.reduce((a,b)=>a+(Number.isFinite(b)?b:5),0)/(axes.length||1);
  const evidence=(scale-avg)*.46+topMatch+secondMatch+boosts[order];
  return {index,score:evidence,order};
 }).sort((a,b)=>b.score-a.score||a.order-b.order);
 const chosen=ranked[0],key=chosen.index===5?p.role+"5":String(chosen.index);
 const choices=group[key],answer=p.choices[chosen.index];
 return Array.isArray(choices)&&choices[answer]?choices[answer]:sections.line;
}
